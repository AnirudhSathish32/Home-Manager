TODAY = {"vision": "receipt-vision-v7-indent", "pdf": "pdf-pages-v4-indent", "group": "receipt-images-v3-indent"}
PAGES = (slice(0, GROUP_SPLIT), slice(GROUP_SPLIT, None))


def answer(selection):
    return v7_answer(BREAKFAST_TEXTS[selection], BREAKFAST_INDENTS[selection])


# The hand checks (no application code) ------------------------------------------------------------------------------

def test_the_inputs_are_the_committed_bytes():
    assert {name: sha256_of(path) for name, path in INPUT_FILES.items()} == INPUT_HASHES


def test_the_capture_files_are_never_rewritten_by_a_checkout():
    lines = (DATA.parent.parent / ".gitattributes").read_text(encoding="utf-8").splitlines()
    assert "tests/reading_format_data/** -text" in lines


def test_mask_port_hides_only_the_port():
    assert mask_port('{"base_url": "http://127.0.0.1:41233/v1"} 127.0.0.1:9') == '{"base_url": "http://127.0.0.1:PORT/v1"} 127.0.0.1:PORT'
    assert mask_port("no address here 127.0.0.2:5") == "no address here 127.0.0.2:5"


def test_dump_vision_requests_hashes_the_image_not_the_bytes():
    import base64
    import hashlib
    image = b"\x89PNG not really"
    request = {"messages": [{"role": "user", "content": [{"type": "text", "text": "data:image/png;base64,"},
                                                         {"type": "image_url", "image_url": {"url": "data:image/png;base64," + base64.b64encode(image).decode()}}]}]}
    text = dump_vision_requests([request])
    assert f"sha256:{hashlib.sha256(image).hexdigest()}" in text and "base64,iVBOR" not in text and text.endswith("]\n")
    assert json.loads(text)[0]["messages"][0]["content"][0]["text"] == "data:image/png;base64,"
    assert dump_vision_requests([request]) == text


def test_v7_answer_is_the_v7_shape():
    assert v7_answer(["a", "b"]) == {"lines": [{"text": "a", "indent": 0}, {"text": "b", "indent": 0}]}
    assert v7_answer(["a", "b"], [1, 2]) == {"lines": [{"text": "a", "indent": 1}, {"text": "b", "indent": 2}]}
    assert len(answer(PAGES[0])["lines"]) + len(answer(PAGES[1])["lines"]) == len(BREAKFAST_TEXTS)


# The capture ------------------------------------------------------------------------------------------------------

def manager_for(tmp_path):
    manager = Manager(tmp_path / "control", ScanLimits(stability_seconds=0))
    manager.configure(str(tmp_path / "managed"))
    return manager


def last_parse(manager, version):
    """The one succeeded parse run of this parser version: (id, parser_version, options_json, result_json)."""
    with manager.store.connection() as db:
        [row] = db.execute("SELECT id,status,options_json,result_json FROM parse_runs WHERE parser_version=?", (version,)).fetchall()
    assert row[1] == "succeeded", row[1]
    return row[2], row[3]


def read_image(tmp_path, local_model):
    manager = manager_for(tmp_path)
    (manager.store.library.inbox / "receipt.png").write_bytes(INPUT_FILES["receipt.png"].read_bytes())
    local_model["output"] = answer(slice(None))
    manager.configure_vision(local_model["config"])
    manager.start_inbox()
    manager.future.result(timeout=60)
    return manager, TODAY["vision"]


def read_pdf(tmp_path, local_model):
    manager = manager_for(tmp_path)
    (manager.store.library.inbox / "scan.pdf").write_bytes(INPUT_FILES["scan.pdf"].read_bytes())
    local_model["output"] = answer(slice(None))
    manager.configure_vision(local_model["config"])
    manager.start_inbox()
    manager.future.result(timeout=60)
    return manager, TODAY["pdf"]


def read_group(tmp_path, local_model):
    manager = manager_for(tmp_path)
    for name, source in (("receipt_p1.png", "page1.png"), ("receipt_p2.png", "page2.png")):
        (manager.store.library.inbox / name).write_bytes(INPUT_FILES[source].read_bytes())
    manager.start_inbox()
    manager.future.result(timeout=60)  # No vision model yet: captured and suggested, not read.
    [group] = manager.suggested_groups()
    manager.configure_vision(local_model["config"])
    local_model["outputs"] = [answer(PAGES[0]), answer(PAGES[1])]
    manager.change_group(group["id"], "confirmed")
    manager.future.result(timeout=60)
    local_model.pop("outputs", None)
    return manager, TODAY["group"]


@pytest.fixture
def model():
    state, stop = start_model_server()
    try:
        yield state
    finally:
        stop()


def write(path, text):
    path.write_text(mask_port(text), encoding="utf-8", newline="")


@capture_only
def test_capture_the_v7_readings(tmp_path_factory, model):
    assert VISION_VERSION == TODAY["vision"] and PDF_VERSION == TODAY["pdf"] and GROUP_VERSION == TODAY["group"]
    assert {name: sha256_of(path) for name, path in INPUT_FILES.items()} == INPUT_HASHES
    DATA.mkdir(exist_ok=True)
    settings = None
    for kind, reader in (("image", read_image), ("pdf", read_pdf), ("group", read_group)):
        model["requests"].clear()
        manager, version = reader(tmp_path_factory.mktemp(kind), model)
        try:
            options, result = last_parse(manager, version)
            requests = list(model["requests"])
            assert requests and all(request["messages"][-1]["content"][-1]["type"] == "image_url" for request in requests)
            assert len(requests) == (2 if kind == "group" else 1), len(requests)
            write(CAPTURES[kind]["requests"], dump_vision_requests(requests))
            write(CAPTURES[kind]["result"], result)
            write(CAPTURES[kind]["options"], options)
            settings = mask_port((manager.control / "vision.json").read_text(encoding="utf-8"))
        finally:
            manager.close()
    SETTINGS.write_text(settings, encoding="utf-8", newline="")
