def manager_for(tmp_path):
    manager = Manager(tmp_path / "control", ScanLimits(stability_seconds=0))
    manager.configure(str(tmp_path / "managed"))
    return manager


def start_reasoning(manager, local_model):
    # After capture, so Inbox's automatic ledger extraction does not run and each step is read on its own.
    manager.configure_reasoning(ReasoningConfig(base_url=local_model["config"].base_url, model="synthetic-reasoning"))
    manager.configure_household(HouseholdConfig(auto_identify_items=False))


def record(manager, local_model, doc_id, parse_id, replies):
    """Extract the parse run with replies: (the stored extraction run, every reasoning request body in order)."""
    local_model["requests"].clear()
    local_model["by_schema"] = {name: list(reply) for name, reply in replies.items()}
    local_model.pop("outputs", None)
    run_id = manager.start_extraction(doc_id, parse_id, False)["run_id"]
    manager.future.result(timeout=60)
    run = manager.extractions.get(run_id)
    assert run["status"] == "succeeded", run["error"]
    assert run["publication"]["status"] == "published"
    assert not any(local_model["by_schema"].values()), f"unused replies: {[name for name, left in local_model['by_schema'].items() if left]}"
    requests = list(local_model["requests"])
    assert requests and all("image_url" not in json.dumps(request) for request in requests)  # Reasoning, never vision.
    return run, requests


def stored_result(manager, parse_id):
    with manager.store.connection() as db:
        status, version, text = db.execute("SELECT status,parser_version,result_json FROM parse_runs WHERE id=?", (parse_id,)).fetchone()
    assert status == "succeeded", status
    return version, text


def read_image(tmp_path, local_model):
    manager = manager_for(tmp_path)
    make_receipt(manager.store.library.inbox / "breakfast.png", BREAKFAST_TEXTS)
    local_model["output"] = old_vision_text(BREAKFAST_TEXTS)
    manager.configure_vision(local_model["config"])
    manager.start_inbox()
    manager.future.result(timeout=60)
    start_reasoning(manager, local_model)
    [doc] = manager.store.documents()["items"]
    [parse] = manager.receipts.history(doc["id"])
    return manager, doc["id"], parse["id"]


