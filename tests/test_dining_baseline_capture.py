def read_group(tmp_path, local_model):
    manager = manager_for(tmp_path)
    for name, texts in (("receipt_p1.png", BREAKFAST_TEXTS[:GROUP_SPLIT]), ("receipt_p2.png", BREAKFAST_TEXTS[GROUP_SPLIT:])):
        make_receipt(manager.store.library.inbox / name, texts)
    manager.start_inbox()
    manager.future.result(timeout=60)  # No vision model yet: captured and suggested, not read.
    [group] = manager.suggested_groups()
    first = group["pages"][0]["document_id"]
    manager.configure_vision(local_model["config"])
    local_model["outputs"] = [old_vision_text(BREAKFAST_TEXTS[:GROUP_SPLIT]), old_vision_text(BREAKFAST_TEXTS[GROUP_SPLIT:])]
    manager.change_group(group["id"], "confirmed")
    manager.future.result(timeout=60)
    local_model.pop("outputs", None)
    start_reasoning(manager, local_model)
    [parse] = [row for row in manager.receipts.history(first) if row["parser_version"] == TODAY["group"]]
    return manager, first, parse["id"]


def row_instruction(requests):
    """Today's receipt row instruction, cut out of the rows request of the extraction run (its text is the `direction` of a dining receipt)."""
    [text] = {content for request in requests for message in request["messages"] if isinstance(message["content"], str)
              for content in [message["content"]] if ROW_INSTRUCTION_START in content}
    start = text.index(ROW_INSTRUCTION_START)
    end = text.index(KIND_ROWS["dining"], start) + len(KIND_ROWS["dining"])
    return text[start:end]


@capture_only
def test_capture_the_v6_readings_and_the_v56_requests(tmp_path_factory, capture_model):
    local_model = capture_model
    assert VISION_VERSION == TODAY["vision"] and PDF_VERSION == TODAY["pdf"] and GROUP_VERSION == TODAY["group"]
    assert EXTRACTION_VERSION == TODAY["extraction"]
    DATA.mkdir(exist_ok=True)
    instructions = set()
    for key, reader, id_of in (("R6", read_image, image_id), ("P3", read_pdf, pdf_id), ("G2", read_group, group_id)):
        manager, doc_id, parse_id = reader(tmp_path_factory.mktemp(key.lower()), local_model)
        try:
            version, text = stored_result(manager, parse_id)
            assert version == TODAY[{"R6": "vision", "P3": "pdf", "G2": "group"}[key]]
            texts, _, replies = breakfast_stub("B0", id_of)
            assert texts == BREAKFAST_TEXTS
            run, requests = record(manager, local_model, doc_id, parse_id, replies)
            assert run["prompt_version"] == TODAY["extraction"] if "prompt_version" in run else True
            CAPTURES["result"][key].write_text(text, encoding="utf-8", newline="")
            CAPTURES["requests"][key].write_text(dump_requests(requests), encoding="utf-8", newline="")
            instructions.add(row_instruction(requests))
        finally:
            manager.close()
    [instruction] = instructions  # The same text for all three readings.
    CAPTURES["row_instruction"].write_text(instruction, encoding="utf-8", newline="")
