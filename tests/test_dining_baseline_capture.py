def citations(node):
    """Every evidence entry in a reply: dicts with a line_id and a quote."""
    if isinstance(node, dict):
        if "line_id" in node and "quote" in node:
            yield node
        for child in node.values():
            yield from citations(child)
    elif isinstance(node, list):
        for child in node:
            yield from citations(child)


